#תשובה:
#1. DFS עובר תחילה לצומת העמוק ביותר מכיוון:
#   - DFS משתמש בגישת "חפש עד מבוי סתום, ואז מסלול אחורה".
#   - בכל פעם שאתה מוצא שכן, עבור ישר לצומת זה (רקורסיה)
#   - אל תפסיק עד שלא יהיו יותר שכנים, אז נסה סניף אחר

#2. אם הסדר השכן שונה:
