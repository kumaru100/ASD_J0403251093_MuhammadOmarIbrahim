# גרף משוקלל עם משקלים שליליים
graph = {
    'A': {'B': 5, 'C': 4},  # A עד B (משקל 5), A עד C (משקל 4)
    'B': {},                  # לב' אין שכנים
    'C': {'B': -2}            # C עד B (משקל שלילי -2)
}

def bellman_ford(graph, start):
    'פונקציה למציאת המרחק הקצר ביותר מצומת ההתחלה\n    לכל שאר הצמתים באמצעות אלגוריתם Bellman-Ford.'
    # אתחול כל המרחקים עם אינסוף כי הם עדיין לא ידועים
    distances = {node: float('inf') for node in graph}

    # המרחק מההתחלה לעצמו הוא תמיד 0
    distances[start] = 0

    # הרפיה מתבצעת כמה פעמים שיש צמתים - פעם אחת
    # כך שבחנו את כל הדרכים הקצרות ביותר האפשריות
    for _ in range(len(graph) - 1):
        # בדוק כל קצה בגרף כולו
        for node in graph:
            for neighbor, weight in graph[node].items():
                # אם מגיעים לצומת ונמצא מרחק קטן יותר,
                # עדכון מרחק לשכן
                if distances[node] != float('inf') and distances[node] + weight < distances[neighbor]:
                    distances[neighbor] = distances[node] + weight

    return distances  # להחזיר את המרחק הקצר ביותר לכל הצמתים

# הפעל את בלמן-פורד החל מהצומת 'A'
hasil = bellman_ford(graph, 'A')

# הצג את התוצאות של המרחק הקצר ביותר מ-A לכל הצמתים
print('המרחק הקצר ביותר מצומת A:')
for node, distance in hasil.items():
    print(node, "=", distance)

